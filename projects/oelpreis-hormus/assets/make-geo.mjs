// Projects Natural Earth 10m land + borders around the Strait of Hormuz into
// a 1920x1080 SVG coordinate space and writes a TS module with path strings.
// Usage: node make-geo.mjs <world-atlas dir> <out.ts>
import { readFileSync, writeFileSync } from "node:fs";
import { geoMercator, geoPath, geoContains } from "d3-geo";
import { merge, mesh } from "topojson-client";

const [dir, out] = process.argv.slice(2);
const countries = JSON.parse(readFileSync(`${dir}/countries-10m.json`, "utf8"));

const W = 1920;
const H = 1080;
// Frame: Persian Gulf (west) to Gulf of Oman (east).
const bbox = {
  type: "Feature",
  geometry: {
    type: "MultiPoint",
    coordinates: [
      [48.6, 23.0],
      [60.6, 30.4],
    ],
  },
};
const projection = geoMercator().fitExtent(
  [
    [0, 0],
    [W, H],
  ],
  bbox,
);
// Clip generously so the camera can zoom out a little without showing edges.
const pad = 400;
projection.clipExtent([
  [-pad, -pad],
  [W + pad, H + pad],
]);

// Land = all countries merged. Antarctica (010) and the Maldives (462) are left
// out: their rings are wound inside-out in the 10m data, so they would cover
// the whole sphere and break the containment test below.
const landFc = merge(
  countries,
  countries.objects.countries.geometries.filter(
    (g) => g.id !== "010" && g.id !== "462",
  ),
);
const borders = mesh(countries, countries.objects.countries, (a, b) => a !== b);

const round = (d) => d.replace(/(\d+\.\d)\d+/g, "$1");
const path = geoPath(projection);
const landD = round(path(landFc));
const bordersD = round(path(borders));

// Tanker route: Persian Gulf → strait (around Musandam) → Gulf of Oman.
const route = [
  [50.3, 27.3],
  [51.6, 27.0],
  [53.0, 26.62],
  [53.9, 26.36],
  [54.6, 26.38],
  [55.5, 26.45],
  [56.1, 26.6],
  [56.45, 26.55],
  [56.7, 26.25],
  [57.1, 25.7],
  [57.8, 25.15],
  [58.7, 24.75],
  [59.8, 24.4],
];
const isLand = (pt) => geoContains(landFc, pt);
// Densify and check every 0.02° along the route for land hits.
for (let i = 1; i < route.length; i++) {
  const [a, b] = [route[i - 1], route[i]];
  for (let t = 0; t <= 1; t += 0.02) {
    const p = [a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t];
    if (isLand(p)) console.warn("route on land near", p.map((v) => v.toFixed(2)).join(","));
  }
}

const proj = (pt) => projection(pt).map((v) => Math.round(v * 10) / 10);
const labels = {
  iran: [54.6, 29.2],
  persischerGolf: [51.6, 26.9],
  golfVonOman: [58.9, 24.0],
  oman: [57.6, 23.35],
  vae: [54.2, 23.7],
  saudiArabien: [49.6, 24.4],
};
const strait = [56.35, 26.45]; // narrowest point between Iran and Musandam

const ts = `// Generated by make-geo.mjs from Natural Earth 10m (world-atlas@2.0.2, public domain).
// Mercator, fitted to lon 48.6–60.6 / lat 23.0–30.4 in a 1920×1080 frame.
// Do not edit by hand — regenerate instead.

/** Land outline (all coasts) in frame coordinates. */
export const LAND_D = ${JSON.stringify(landD)};

/** Land borders between countries. */
export const BORDERS_D = ${JSON.stringify(bordersD)};

/** Tanker route, Persian Gulf → Strait of Hormuz → Gulf of Oman, in frame coordinates. */
export const ROUTE: ReadonlyArray<readonly [number, number]> = ${JSON.stringify(route.map(proj))};

/** Narrowest point of the Strait of Hormuz. */
export const STRAIT: readonly [number, number] = ${JSON.stringify(proj(strait))};

/** Label anchors (centre of the label). */
export const LABELS = ${JSON.stringify(Object.fromEntries(Object.entries(labels).map(([k, v]) => [k, proj(v)])), null, 2)} as const;
`;
writeFileSync(out, ts);
console.log("land chars", landD.length, "borders chars", bordersD.length, "strait", proj(strait));
